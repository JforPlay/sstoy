import { strict as assert } from 'node:assert';
const { chromium } = await import(process.env.STELLA_PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1080 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
  await page.goto(process.env.STELLA_TEST_URL || 'http://localhost:3000/app.html');
  await page.getByText('데미지 계산기 BETA', { exact: true }).click();
  const setup = page.locator('[data-calc-section="1"]');
  if (await setup.getAttribute('open') === null) await setup.locator('summary').first().click();
  await page.locator('[data-action="calc-ingame-preset"]').click();
  await page.locator('#ingame-code-import-input').fill('AAAAogAAAHMAAABrzbAB4YbBiAgMAGwAIAQQ');
  await page.locator('[data-action="saveload-ingame-import"]').click();
  await page.locator('#ingame-code-modal').waitFor({ state: 'detached' });
  await page.getByText('데미지 계산기 BETA', { exact: true }).click();
  const step = page.locator('[data-calc-section="6"]');
  if (!await step.getAttribute('open').then(value => value !== null)) await step.locator('summary').first().click();
  await page.locator('[data-action="cycle-search"]').click();
  await page.locator('[data-action="cycle-candidate"]').first().waitFor({ timeout: 120000 });
  assert.equal(await page.locator('[data-action="cycle-candidate"]').count(), 3);
  assert.equal(await page.locator('#dmgcalc-cycle [role="alert"]').count(), 0);
  console.log((await page.locator('#dmgcalc-cycle').innerText()).slice(0, 4000));
  await page.locator('#dmgcalc-cycle').screenshot({ path: 'reports/rotation-cycle-desktop.png' });
  await page.getByText('사용 시각 · SP · 횟수 확인', { exact: true }).click();
  assert.ok(await page.locator('.dmgcalc-cycle-table tbody tr').count() > 30);
  const scores = await page.locator('#dmgcalc-cycle .dmgcalc-key-stats strong').allTextContents();
  const maximumOption = await page.locator('[data-cycle-setting="technicalCount"] option').last().getAttribute('value');
  await page.locator('[data-cycle-setting="technicalCount"]').selectOption(maximumOption);
  const withTechnical = await page.locator('#dmgcalc-cycle .dmgcalc-key-stats strong').allTextContents();
  const parse = value => Number(value.replaceAll(',', ''));
  assert.equal(parse(withTechnical[2]) - parse(scores[2]), 5400);
  await page.locator('[data-action="cycle-candidate"][data-index="1"]').click();
  assert.equal(await page.locator('[data-action="cycle-candidate"][data-index="1"]').getAttribute('aria-pressed'), 'true');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('#dmgcalc-cycle').screenshot({ path: 'reports/rotation-cycle-mobile.png' });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false, 'page must not overflow horizontally');
  const otherBoss = await page.locator('[data-cycle-setting="boss"] option').first().getAttribute('value');
  await page.locator('[data-cycle-setting="boss"]').selectOption(otherBoss);
  await page.locator('[data-cycle-setting="cinematics"]').uncheck();
  await page.locator('[data-action="cycle-search"]').click();
  await page.locator('[data-action="cycle-cancel"]').click();
  assert.equal(await page.locator('[data-action="cycle-search"]').isEnabled(), true);
  assert.deepEqual(errors, []);
  console.log('Cycle UI: results, SP table, technical score, candidate switch, mobile layout and cancellation passed.');
} finally { await browser.close(); }
